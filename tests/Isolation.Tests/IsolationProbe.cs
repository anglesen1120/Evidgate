namespace Isolation.Tests;

/// <summary>
/// 01.6.1-T4: the probe statements of the isolation suite, kept in one place so the
/// normal tests and <c>Isolation_PlantedViolation_Fails</c> share the exact same
/// read — the meta-test asserts the leak through it, not through a look-alike.
/// </summary>
internal static class IsolationProbeSql
{
    /// <summary>
    /// The production read shape of <c>GET /v1/projects/{p}</c>: the same column list
    /// and order as <c>Evidgate.Modules.Tenancy.Infrastructure.Persistence.
    /// TenancyReadSql.ProjectById</c>, materialised into the public
    /// <see cref="Evidgate.Modules.Tenancy.Contracts.ProjectDto"/>. The statement is
    /// internal to the module and this project deliberately has no
    /// <c>InternalsVisibleTo</c> to it; the column/parameter contract that must not
    /// drift is pinned against the DTO by <c>ReadSqlContractTests</c> and
    /// <c>ReadSqlMaterializationTests</c>. The tenant filter is never a predicate —
    /// row level security supplies it, which is what the tests around it prove.
    /// </summary>
    internal const string ProjectById = """
        select id,
               org_id,
               name,
               slug,
               status,
               default_environment_id,
               created_at,
               updated_at,
               version,
               retention_days,
               monthly_run_quota
          from public.project
         where id = @project_id
        """;
}

/// <summary>
/// The EF Core write-model probe over <c>public.project</c> (migration 0005), the
/// representative business table of 01.6.1-T4.1. The entity is named
/// <c>Project</c> on purpose: 01.4.2-T1.3's model conventions derive the table from
/// the snake_case singular CLR name and every column from the snake_case property
/// name, so this class lands on the production table and its columns with no
/// explicit mapping at all — the same convention the module's own
/// <c>ProjectConfiguration</c> spells out by hand. (The module's entity stays
/// internal there — 00 §5.5 — and this project intentionally does not see it.)
/// </summary>
internal sealed class Project
{
    /// <summary>UUIDv7, generated by the caller (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>The tenant key the row-level-security policy filters on.</summary>
    public Guid OrgId { get; set; }

    /// <summary>Display name, ≤ 128 chars (check constraint of 0005).</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>Onboarding slug, unique per org; the 0005 grammar.</summary>
    public string Slug { get; set; } = string.Empty;

    /// <summary>One of active / suspended / deleted (0005 check).</summary>
    public string Status { get; set; } = "active";

    /// <summary>05.1.2-T1's column; always null for the probe.</summary>
    public Guid? DefaultEnvironmentId { get; set; }

    /// <summary>UTC creation timestamp (00 §5.4.4).</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>UTC last-write timestamp.</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic-concurrency token, starts at 1 (00 §7).</summary>
    public int Version { get; set; } = 1;
}

/// <summary>
/// The smallest <see cref="EvidgateDbContext"/> the EF isolation probe needs: one
/// DbSet, the production conventions via <c>UseTenantModel</c> and the
/// <see cref="TenantCommandInterceptor"/> so the AC1 guard of 01.4.2-T1.5 stays on
/// the path (a context without it would bypass the guard the tests rely on).
/// </summary>
internal sealed class IsolationProbeContext(DbContextOptions<IsolationProbeContext> options)
    : EvidgateDbContext(options)
{
    /// <summary>The write-model view of <c>public.project</c>.</summary>
    internal DbSet<Project> Projects => Set<Project>();
}

/// <summary>Builds the probe context the production way: scope connection, scope transaction, interceptor.</summary>
internal static class IsolationProbe
{
    /// <summary>
    /// Creates a context bound to <paramref name="scope"/> exactly as
    /// <c>TenantDbContextFactory&lt;TContext&gt;.Create</c> does for a module
    /// (01.4.2-T1.3): <c>UseNpgsql</c> on the scope's connection,
    /// <c>UseTenantModel</c> over an assembly of configurations (the probe has none —
    /// the conventions do the mapping), the shared
    /// <see cref="TenantCommandInterceptor"/> and <c>UseTransaction</c> over the
    /// scope's transaction, so an EF read sees the Dapper writes of the same scope.
    /// </summary>
    internal static IsolationProbeContext CreateContext(
        TenantTestScope scope,
        TenantCommandInterceptor interceptor)
    {
        var options = new DbContextOptionsBuilder<IsolationProbeContext>()
            .UseNpgsql(scope.Connection)
            .AddInterceptors(interceptor)
            .UseTenantModel(typeof(IsolationProbeContext).Assembly)
            .Options;

        var context = new IsolationProbeContext(options);
        context.Database.UseTransaction(scope.Transaction);
        return context;
    }
}
