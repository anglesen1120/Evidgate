/// <summary>
/// The measurement class reads process-wide memory, so it never runs beside another collection: a neighbour's
/// allocations would land in this process's retained bytes.
/// </summary>
[CollectionDefinition(Name, DisableParallelization = true)]
public sealed class LargeReportBudgetGroup
{
    /// <summary>The collection name the budget class joins.</summary>
    public const string Name = "Large report budget";
}

/// <summary>
/// The 100 000-test fixture through the whole path: the real parse child turns the generated report into events and
/// attempts, the real reconciler reads the run, and the attempts route is paged to its end. Each phase's wall time and
/// the two memory numbers are compared with the fixture's <c>budget</c> member; while that member is <c>unset</c> the
/// test only measures, prints and fails, which is what the quiet-host timing run reads.
/// </summary>
[Trait("Category", "Budget")]
[Trait("Category", "Docker")]
[Collection(LargeReportBudgetGroup.Name)]
public sealed partial class LargeReportBudgetTests(
    PostgresTenancyFixture fixture,
    SeaweedFsStore store,
    TenancyHostPool hosts,
    ITestOutputHelper output)
    : IClassFixture<SeaweedFsStore>, IClassFixture<TenancyHostPool>
{
    /// <summary>The registry's producer kind for a pytest JUnit XML report.</summary>
    private const string ProducerKind = "pytest-junitxml";

    /// <summary>The media type the fixture's report is stored and sniffed as.</summary>
    private const string XmlType = "application/xml";

    /// <summary>The fixture's declared size; the generator is asked for exactly this many testcases.</summary>
    private const int PlannedExecutions = 100_000;

    /// <summary>The fixture's seed, so the generated bytes are the pinned ones.</summary>
    private const int Seed = 1;

    /// <summary>The attempts route's largest page, so the walk spends the fewest round trips it can.</summary>
    private const int PageLimit = 200;

    private static readonly string FixtureDirectory = FixtureLoader.Fixtures("large/100k-tests");

    private static readonly JsonElement Expected =
        JsonDocument.Parse(File.ReadAllText(Path.Combine(FixtureDirectory, "expected.json"))).RootElement.Clone();

    /// <summary>A parse child that outlives the production 30 s wall clock is a measurement artefact, not a breach.</summary>
    private static readonly TimeSpan PhaseCeiling = TimeSpan.FromMinutes(10);

    private readonly PostgresTenancyFixture _fixture = fixture;

    private readonly SeaweedFsStore _store = store;

    private static CancellationToken Token => TestContext.Current.CancellationToken;

    [Fact]
    public async Task LargeReport_100k_ParseReconcileCompare_WithinBudget()
    {
        var budget = ReportBudget.Read(Expected);
        using var temp = new TempDirectory();
        var report = GenerateReport(temp.Path);

        await using var database = await _fixture.CreateDedicatedDatabaseAsync();
        await using var world = await StartAsync(database.Name);
        await using var stored = new StoredObject(_store, await SeedArtifactAsync(world, report));
        var artifact = stored.Artifact;

        var parentBefore = ParentWorkingSet.Peak();
        var baseline = ParentRetainedSampler.Baseline();

        long parseWall;
        long childPeak;
        long parentRetained;
        ParseRawReportOutcome parsed;

        var child = ChildWorkingSetSampler.Start(ParseChildAssembly.Locate(), TimeSpan.FromMilliseconds(250));
        var parent = ParentRetainedSampler.Start(baseline, TimeSpan.FromSeconds(2));
        try
        {
            var started = Stopwatch.StartNew();
            parsed = await ParseAsync(world, artifact.Id, Path.Combine(temp.Path, "child"));
            started.Stop();
            parseWall = started.ElapsedMilliseconds;
        }
        finally
        {
            await child.DisposeAsync();
            await parent.DisposeAsync();
        }

        childPeak = child.PeakWorkingSetBytes;
        parentRetained = parent.PeakRetainedBytes;
        parsed.Status.ShouldBe(ParseRawReportOutcome.Parsed, "the fixture report must parse through the real child");
        parsed.Events.ShouldBe(PlannedExecutions);

        await RunStateWalk.MoveAsync(_fixture, world.Database, world.RunId, RunStates.Collecting);
        var reconciling = Stopwatch.StartNew();
        var reconciled = await ReconcileAsync(world);
        reconciling.Stop();
        reconciled.Disposition.ShouldBe(ReconcileDisposition.Compared,
            "a collecting run whose plan is fully answered compares; any other disposition means the phase measured nothing");

        var walk = await WalkAttemptsAsync(world);
        var measured = new BudgetMetrics(
            parseWall, reconciling.ElapsedMilliseconds, walk.WallMs, childPeak, parentRetained);

        var parentAfter = ParentWorkingSet.Peak();
        Print(measured, child, parent, parentBefore, parentAfter, walk);

        var verdict = budget.Compare(measured);
        verdict.WithinBudget.ShouldBeTrue(verdict.Message);
    }

    /// <summary>The world: one dedicated database's tenant and project, plus a run a report can move.</summary>
    private async Task<World> StartAsync(string database)
    {
        Guid user;
        Guid org;
        Guid project;

        await using (var api = hosts.RealResolver(database))
        using (var setup = api.CreateClient())
        {
            user = Guid.CreateVersion7();
            org = await CreateOrgAsync(setup, user, Unique.Slug("budget"));
            project = await CreateProjectAsync(setup, user, org, Unique.Slug("report"));
        }

        // A member carries run:read, which the attempts route asks for; the parse handler runs in-process, so the
        // published principal never decides whether the report is admitted.
        var host = TenancyApiFactory.WithPrincipal(
            _fixture.AppConnectionString(database), org, project, RequestPrincipal.Member(user), _store.Configuration());
        var client = host.CreateClient();
        var runId = await RunRowSeeder.SeedRunAsync(_fixture, database, org);

        // `created` is never persisted: the run a report can move is the one the create transaction wrote `queued`.
        await _fixture.ExecuteAsync(database, $"update public.run set state = 'queued' where id = '{runId:D}'");

        return new World(host, client, database, org, project, runId);
    }

    /// <summary>The call the task consumer makes, minus the queue, with the real out-of-process runner.</summary>
    private static async Task<ParseRawReportOutcome> ParseAsync(World world, Guid artifactId, string childTempRoot)
    {
        var services = world.Host.Services;

        // The caps are raised above the production 30 s wall clock: a budget run must not report a timeout as a parse.
        using var runner = new ChildProcessParseRunner(
            new ParseRunnerOptions
            {
                ChildPath = ParseChildAssembly.Locate(),
                TempRoot = childTempRoot,
                CpuSeconds = (int)PhaseCeiling.TotalSeconds,
                WallClockSeconds = (int)PhaseCeiling.TotalSeconds,
            },
            ChildCommandLine.ForOptions);

        var handler = new ParseRawReportHandler(
            services.GetRequiredService<ITenantScopeFactory>(),
            services.GetRequiredService<ITenantDbContextFactory<EvidenceDbContext>>(),
            services.GetRequiredService<ITenantDb>(),
            services.GetRequiredService<IObjectStorage>(),
            services.GetRequiredService<IReportParserResolver>(),
            runner,
            services.GetRequiredService<IOptions<IngestionLimits>>(),
            services.GetServices<IJUnitMapper>(),
            services.GetRequiredService<IServiceScopeFactory>(),
            services.GetRequiredService<IOutboxWriter>(),
            services.GetRequiredService<IAuditTrail>(),
            services.GetRequiredService<TimeProvider>(),
            NullLogger<ParseRawReportHandler>.Instance);

        return await handler.ExecuteAsync(new ParseRawReportPayload(world.RunId, artifactId, ProducerKind), world.Org, Token);
    }

    /// <summary>One reconcile of the run, in its own committed tenant transaction, the way the consumer runs it.</summary>
    private static async Task<ReconcileOutcome> ReconcileAsync(World world)
    {
        await using var services = world.Host.Services.CreateAsyncScope();
        await using var scope = await services.ServiceProvider.GetRequiredService<ITenantScopeFactory>()
            .BeginAsync(world.Org, null, false, Token);
        var outcome = await services.ServiceProvider.GetRequiredService<IRunReconciler>()
            .ReconcileAsync(world.RunId, lateTrigger: false, reprocessTrigger: false, Token);

        await scope.CommitAsync();

        return outcome;
    }

    /// <summary>
    /// Pages the attempts route to its end. The rows are ordered by <c>(execution_key, attempt_no)</c>, so a strictly
    /// ascending walk of 100 000 rows is itself the proof that no execution was served twice.
    /// </summary>
    private async Task<Walk> WalkAttemptsAsync(World world)
    {
        var started = Stopwatch.StartNew();
        var rows = 0;
        var pages = 0;
        var ordered = true;
        string? previous = null;
        string? cursor = null;

        for (var page = 0; page <= PlannedExecutions / PageLimit; page++)
        {
            var query = $"?limit={PageLimit}" + (cursor is null ? string.Empty : $"&cursor={Uri.EscapeDataString(cursor)}");
            var answer = await world.Client.SendAsync(HttpMethod.Get, $"/v1/runs/{world.RunId}/attempts{query}", _ => { });
            answer.Status.ShouldBe(HttpStatusCode.OK, answer.ErrorMessage);
            pages++;

            foreach (var item in answer.Body.GetProperty("items").EnumerateArray())
            {
                var key = item.GetProperty("execution_key").GetString()!;
                ordered &= previous is null || string.CompareOrdinal(previous, key) < 0;
                previous = key;
                rows++;
            }

            cursor = answer.Body.GetProperty("next_cursor").GetString();
            if (cursor is null)
            {
                break;
            }
        }

        started.Stop();

        rows.ShouldBe(PlannedExecutions, "every planned execution answers once, so the walk sees the whole plan");
        ordered.ShouldBeTrue("the page is ordered by (execution_key, attempt_no), so a repeated key means a repeated row");
        cursor.ShouldBeNull("the last page's next_cursor ends the walk");

        var uncovered = await _fixture.ScalarAsync<long>(
            world.Database,
            $"""
            select count(*) from public.planned_execution pe
             where pe.org_id = '{world.Org:D}' and pe.run_id = '{world.RunId:D}'
               and not exists (
                   select 1 from public.case_attempt a
                    where a.org_id = pe.org_id and a.run_id = pe.run_id and a.execution_key = pe.execution_key)
            """);
        uncovered.ShouldBe(0, "each planned execution must be covered by the attempt the walk served");

        return new Walk(started.ElapsedMilliseconds, rows, pages);
    }

    private void Print(
        BudgetMetrics measured,
        ChildWorkingSetSampler child,
        ParentRetainedSampler parent,
        (long Bytes, string Source) parentBefore,
        (long Bytes, string Source) parentAfter,
        Walk walk)
    {
        foreach (var line in measured.Lines())
        {
            output.WriteLine($"budget {line}");
        }

        output.WriteLine($"budget walk pages={walk.Pages} rows={walk.Rows}");
        output.WriteLine($"budget child peak source: {child.Method}, {child.Samples} samples");
        output.WriteLine($"budget parent retained source: forced-GC managed heap, {parent.Samples} samples "
            + "(each sample pauses the parse; the retained peak is a floor)");
        output.WriteLine(string.Create(CultureInfo.InvariantCulture,
            $"budget parent working set before={parentBefore.Bytes} after={parentAfter.Bytes} "
            + $"source={parentAfter.Source} (printed, not asserted)"));
        output.WriteLine($"budget host {Environment.MachineName} {Environment.OSVersion.VersionString}");
    }

    private sealed record World(TenancyApiFactory Host, HttpClient Client, string Database, Guid Org, Guid Project, Guid RunId)
        : IAsyncDisposable
    {
        public async ValueTask DisposeAsync()
        {
            Client.Dispose();
            await Host.DisposeAsync();
        }
    }

    internal sealed record Artifact(Guid Id, string ObjectKey);

    private sealed record Walk(long WallMs, int Rows, int Pages);
}
