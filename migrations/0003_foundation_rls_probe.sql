-- Owner: 01.4.1-T3.3. `public.rls_probe` is the copyable business-table
-- template: the isolation suite (01.4.1-T3.4, extended by 01.6.1-T4) proves the
-- tenancy contract on it, and every later module table copies this shape.
--
-- ============================================================================
-- COPY THIS BLOCK INTO EVERY NEW BUSINESS-TABLE MIGRATION (00 §5.4, §7, F5)
-- ============================================================================
--   1. `org_id uuid not null` on every business row, plus a unique key on
--      `(org_id, id)` — primary key or unique constraint. It is the only target
--      a composite tenant foreign key may reference (00 §5.4.1/§5.4.6):
--        foreign key (org_id, other_id) references other_table (org_id, id)
--   2. `id uuid not null` (UUIDv7 generated by the application, 00 §7),
--      `created_at timestamptz not null default now()`,
--      `updated_at timestamptz not null default now()`,
--      `version integer not null default 1` (optimistic concurrency, 00 §7).
--   3. `alter table … enable row level security;` AND
--      `alter table … force row level security;` — without FORCE the table
--      owner bypasses every policy (DECISIONS F5).
--   4. One policy for `evidgate_app` with BOTH `using` and `with check`,
--      comparing `org_id` to `evidgate.current_org_id()` — never raw
--      `current_setting`, so a missing tenant context yields zero rows instead
--      of an error or every row (TL T2). Add `evidgate.current_project_id()`
--      to the predicate only for project-scoped tables.
--   5. One SELECT-only policy for `evidgate_operator` (audited read path, T76);
--      it holds no DML grant, so the read path cannot mutate.
--   6. One permissive policy for `evidgate_owner`. `FORCE ROW LEVEL SECURITY`
--      applies to the table owner as well, so without a policy for it the
--      migration role silently updates ZERO rows: an expand/contract backfill
--      (`update … set title = label`) and every owner `SECURITY DEFINER` sweep
--      (TL T80) would look successful and change nothing. This is an explicit
--      policy, not a bypass — no role gets BYPASSRLS (DECISIONS F5).
--   7. Grants: `select, insert, update, delete … to evidgate_app` and
--      `select … to evidgate_operator`. Migrations run by evidgate_owner in
--      schema `public` also inherit the default privileges from 0001; repeat
--      the grant for a table created by another role or in a new schema.
-- ============================================================================

create table if not exists public.rls_probe (
  org_id uuid not null,
  id uuid not null,
  label text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  version integer not null default 1,
  constraint rls_probe_pkey primary key (org_id, id)
);

alter table public.rls_probe enable row level security;
alter table public.rls_probe force row level security;

drop policy if exists rls_probe_app_all on public.rls_probe;
create policy rls_probe_app_all on public.rls_probe
  for all
  to evidgate_app
  using (org_id = evidgate.current_org_id())
  with check (org_id = evidgate.current_org_id());

drop policy if exists rls_probe_operator_read on public.rls_probe;
create policy rls_probe_operator_read on public.rls_probe
  for select
  to evidgate_operator
  using (org_id = evidgate.current_org_id());

-- The migration role needs its own policy: `force row level security` applies to
-- the table owner too, so an expand/contract backfill or an owner SECURITY
-- DEFINER sweep would otherwise update zero rows without failing. Explicit and
-- permissive on purpose — the alternative would be BYPASSRLS, which DECISIONS F5
-- rejects.
drop policy if exists rls_probe_owner_backfill on public.rls_probe;
create policy rls_probe_owner_backfill on public.rls_probe
  for all
  to evidgate_owner
  using (true)
  with check (true);

grant select, insert, update, delete on public.rls_probe to evidgate_app;
grant select on public.rls_probe to evidgate_operator;
revoke all on public.rls_probe from evidgate_worker_sched;
