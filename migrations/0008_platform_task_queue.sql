-- 0008_platform_task_queue.sql
--
-- Owner: 01.5.1-T1.1 (slice B2). `task` is the durable internal queue of
-- 00 §5.3: the worker's dispatcher moves committed `outbox` rows (0006) into it
-- as `task` rows, and `Evidgate.Worker` consumers claim rows with
-- `for update skip locked`, run one idempotent handler, and finish the row. Cron
-- schedules fire the same way: the schedule runner inserts one row per due
-- occurrence and lets the unique `(schedule_name, fire_at)` key — never a leader
-- — decide who wins.
--
-- Mechanism table, not a business row (01.5.1 §3, area §4):
--   * `org_id` is NULLABLE: platform work (`idempotency.purge`, `task.sweep`)
--     has no tenant, and a tenant task carries the org its handler opens
--     `ITenantScope` from (`… BeginAsync(task.org_id)`), which is where the
--     tenant boundary is enforced — one hop after the claim.
--   * It deliberately gets NO row level security policy. The claim query scans
--     whatever queue it polls and the dispatcher scans across orgs by design; a
--     tenant policy would silently hide work. Nothing in this table is tenant
--     data: the payload references aggregates by id (00 §5.7 S3).
--
-- State machine (01.5.1 §6, internal to the mechanism — not a business state):
--   queued → active (a consumer claimed the row and holds a lease)
--   active → done   (handler returned)
--   active → retry  (handler threw, attempts < max_attempts; available_at is
--                    pushed out by the backoff helper)
--   active → dead_letter (attempts >= max_attempts, `last_error` holds the
--                    redacted category and message head; visible to operators)
--   dead_letter → queued (operator replay, 01.5.1-T4.2 — never by a consumer)
--   An `active` row whose lease (`locked_until`) expires without a completion is
--   flipped back to `queued` and is claimable again: the crashed-worker path.
--
-- Keys and indexes (01.5.1 §4):
--   * `task_pkey` on `id` — UUIDv7 generated by the application (00 §7).
--   * `task_idem_uq` on `idempotency_key` — at-least-once delivery (A10) is only
--     safe because inserting the same piece of work twice is a no-op. The
--     dispatcher derives `'outbox:' || outbox.id` (01.5.1-T3), a schedule fire
--     derives `'schedule:' || schedule_name || ':' || fire_at`, and a module
--     writer uses `<module>:<aggregate>:<op>` like the outbox key (01.5.1-T2.2).
--   * `task_fire_uq` on `(schedule_name, fire_at) where schedule_name is not
--     null` — the 00 §5.3 guarantee: every worker computes the same due
--     occurrence, every worker tries to insert it, and the unique index means
--     exactly one row exists per fire. There is no leader election and no
--     schedule state row: the fire key is the idempotency.
--   * `task_claim_idx` on `(queue, available_at) where state in ('queued','retry')`
--     — the claim query's scan order (00 §5.7 P4). `task_type = any(...)` and
--     `attempts < max_attempts` are heap-level filters on it by design: the
--     planner keeps it when the claimable set is large (measured: 500 000 due
--     rows, Index Scan, 50 rows read).
--   * `task_claim_type_idx` on `(queue, task_type, available_at) where state in
--     ('queued','retry')` — the version-skew case: a queue carrying a backlog of
--     a task_type this release cannot run is otherwise walked on every poll of
--     every worker (measured 2026-09-26 on postgres:18.6: 1.01 ms at no backlog,
--     5.61 ms + Seq Scan at 100 000 unrunnable due rows; with this index the
--     same statement is 1.01 ms and reads ~150 index entries).
--   * `task_active_idx` on `(queue, locked_until) where state = 'active'` — the lease
--     reclaim (`ReclaimExpiredLeases`) scans exactly this predicate. Without it that
--     statement is a sequential scan of the whole table on every poll of every
--     queue, and a measured 15–18 ms per poll at 100k rows is paid continuously;
--     with it the reclaim visits only the rows a worker currently holds. 00 §5.7 P4
--     ("every scan has an index") and 01.5.1 §8 P4 are why it is here and not in a
--     later migration.
--   * `task_dead_idx` on `(created_at, id) where state = 'dead_letter'` — the
--     operator's keyset list `(created_at, id)` (00 §9.1, 01.5.1-T4.2).
--   * `task_terminal_idx` on `(created_at) where state in ('done','dead_letter')`
--     — the 30-day retention sweep (`task.sweep`, T11/01.5.1 §7).
--
-- `created_at` / `updated_at` / `version` plus the shared
-- `set_updated_at_and_version()` trigger (0004): a task row is read-modify-written
-- many times over its life (every claim, retry, completion), which is exactly the
-- shape 00 §7's version column is for — a stale writer that lost its lease must
-- not be able to overwrite a newer attempt's outcome.
--
-- Grants (00 §5.4.3 least privilege). 0001's default privileges hand
-- `evidgate_app` DML and `evidgate_operator` SELECT on every table
-- `evidgate_owner` creates in `public`; the explicit statements below keep only
-- what the mechanism needs:
--   * `evidgate_app`: select/insert/update/delete. The worker's consumers run as
--     this role — the app role is the only DML role in the system — and the
--     DELETE is the retention sweep's (`task.sweep` deletes terminal rows older
--     than 30 days, 01.5.1 §7/T11), not an ad-hoc path: no command may delete a
--     task, and there is no HTTP route that does.
--   * `evidgate_operator`: nothing. A mechanism table has no policy, so an
--     operator SELECT grant would be standing cross-org read access to every
--     task payload, outside T76's audited grant gate. The operator's dead-letter
--     list (01.5.1-T4.2) adds the read path it needs — a grant or an owner
--     `SECURITY DEFINER` reader — in its own migration, deliberately and with the
--     audit trail attached.
--   * `evidgate_worker_sched`: nothing. This role exists to CALL owner
--     `SECURITY DEFINER` sweeps (TL T80); `idempotency.purge`'s row is an
--     ordinary platform task claimed by the app-role consumer, and the handler
--     opens a `evidgate_worker_sched` connection only for the function call
--     itself. The sweep role never touches a table.

create table if not exists public.task (
  id uuid not null,
  org_id uuid,
  queue text not null,
  task_type text not null,
  payload jsonb not null,
  idempotency_key text not null,
  schedule_name text,
  fire_at timestamptz,
  state text not null default 'queued',
  attempts integer not null default 0,
  max_attempts integer not null default 8,
  available_at timestamptz not null default now(),
  locked_until timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  version integer not null default 1,
  constraint task_pkey primary key (id),
  constraint task_state_check check (state in ('queued', 'active', 'retry', 'dead_letter', 'done')),
  -- A fire key is a pair: `schedule_name` without `fire_at` would insert a row the
  -- schedule runner can never see again (and `fire_at` alone would be meaningless).
  constraint task_fire_pair_check check ((schedule_name is null) = (fire_at is null)),
  constraint task_attempts_check check (attempts >= 0),
  constraint task_max_attempts_check check (max_attempts >= 1),
  -- Input limits (00 §5.7 S3): every field a producer can fill is bounded, so a
  -- task row stays small and `last_error` cannot become an unbounded log sink. The
  -- payload cap is 64 KiB (pg_column_size): a task is a pointer to work, not the
  -- work itself — larger inputs belong in object storage (00 §6).
  constraint task_queue_length_check check (char_length(queue) between 1 and 64),
  constraint task_type_length_check check (char_length(task_type) between 1 and 128),
  constraint task_idempotency_key_length_check check (char_length(idempotency_key) between 1 and 256),
  constraint task_schedule_name_length_check check (schedule_name is null or char_length(schedule_name) between 1 and 128),
  constraint task_last_error_length_check check (last_error is null or char_length(last_error) <= 1000),
  constraint task_payload_size_check check (pg_column_size(payload) <= 65536)
);

create unique index if not exists task_idem_uq on public.task (idempotency_key);
create unique index if not exists task_fire_uq on public.task (schedule_name, fire_at) where schedule_name is not null;
create index if not exists task_claim_idx on public.task (queue, available_at) where state in ('queued', 'retry');
create index if not exists task_claim_type_idx on public.task (queue, task_type, available_at) where state in ('queued', 'retry');
create index if not exists task_active_idx on public.task (queue, locked_until) where state = 'active';
create index if not exists task_dead_idx on public.task (created_at, id) where state = 'dead_letter';
create index if not exists task_terminal_idx on public.task (created_at) where state in ('done', 'dead_letter');

drop trigger if exists task_set_updated_at_and_version on public.task;
create trigger task_set_updated_at_and_version
  before update on public.task
  for each row
  execute function public.set_updated_at_and_version();

-- No EXECUTE grant on `public.set_updated_at_and_version()` here: 0004 already
-- granted it to evidgate_app for this one shared function, and the trigger does not
-- need it at fire time anyway. The EXECUTE check on a trigger function happens when
-- the trigger is created (as the owner), not for the role that later fires it —
-- probed on the pinned postgres:18.6: after `revoke execute on function
-- public.set_updated_at_and_version() from evidgate_app`, an app-role UPDATE of a
-- table carrying this trigger still succeeds. (The claim in 0004's header that
-- without the grant "every app-role UPDATE would fail with 42501" is wrong on this
-- point; the grant there is harmless and stays.)

grant select, insert, update, delete on public.task to evidgate_app;
revoke all on public.task from evidgate_operator;
revoke all on public.task from evidgate_worker_sched;
