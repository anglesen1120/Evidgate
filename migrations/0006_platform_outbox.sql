-- 0006_platform_outbox.sql
--
-- Owner: 01.5.1-T2.1 (slice B1). `outbox` is the transactional outbox of
-- 00 §5.3 / §5.5 C7: a command writes one row inside its own tenant transaction
-- (`evidgate_app`, the `ITenantScope` connection), so the row commits or rolls
-- back with the business change; the worker's dispatcher (01.5.1-T3) later moves
-- it into the `task` queue. Writing a row here is never a second connection and
-- never a second transaction — the whole point is that there is no window in
-- which the business change is committed and the work to be done is not.
--
-- Mechanism table, not a business row (01.5.1 §3, area §4):
--   * it carries `org_id` (every outbox row is written from a tenant
--     transaction, so the tenant is always known), but it deliberately gets NO
--     row level security policy: the dispatcher scans across orgs by design —
--     that is what "move every committed row into the queue" means — so a
--     tenant-scoped policy would make the mechanism silently drop work. The
--     tenant boundary is enforced one hop later, where the handler opens
--     `ITenantScope` from `task.org_id` (§8 S1) and RLS applies to everything it
--     touches.
--     Residual risk, stated because no policy can express it: `evidgate_app` may
--     INSERT a row whose `org_id` is not the scope's tenant, and nothing in the
--     database prevents it. A row policy cannot be the guard — it would break the
--     cross-org dispatcher scan the mechanism exists for — and a `before insert`
--     trigger comparing `new.org_id` to `evidgate.current_org_id()` would not be a
--     boundary either: the app role sets that setting itself, so a statement that
--     intends to write as another tenant passes the check by opening the scope as
--     that tenant. What does hold is the write path: `IOutboxWriter` takes `org_id`
--     from the ambient scope and never from a caller argument (01.5.1-T2.2), so
--     the only way to forge a row is to bypass the writer with hand-written SQL —
--     the same property `task` (0008) has. If that ever needs to be enforced in
--     the database, it belongs on both mechanism tables at once, not here.
--   * It has no `updated_at` / `version`: rows are insert-only until the
--     dispatcher stamps `dispatched_at` once (`... where dispatched_at is null`),
--     so there is no read-modify-write to make optimistic. 00 §7's version column
--     is for rows that are updated; the `task` queue (0008) carries it because a
--     task row is rewritten on every claim, retry and completion, and a mechanism
--     table that is only ever appended to has nothing to lose to a lost update.
--   * `created_at` is the only time column the mechanism needs: it orders the
--     undispatched scan and measures `task_dispatch_lag_seconds` (01.5.1 §7).
--
-- Keys, and what each is for:
--   * `outbox_pkey` on `id` — UUIDv7 generated by the application (00 §7).
--   * `outbox_org_id_uq` on `(org_id, id)` — the 00 §5.4.6 composite-tenant key
--     (TL T3), so a later table can hold `foreign key (org_id, outbox_id)
--     references outbox (org_id, id)` and can never point at another tenant's row.
--   * `outbox_org_idem_uq` on `(org_id, idempotency_key)` — the dedupe key of
--     00 §5.3 A10: a producer that flushes the same command twice (retry,
--     re-delivery) gets 23505 instead of a second piece of work. The convention
--     is `<module>:<aggregate>:<op>` (01.5.1-T2.2), e.g.
--     `identity:organization:created`; the dispatcher derives the `task` key as
--     `'outbox:' || outbox.id`, which is what makes duplicate dispatch harmless.
--   * `outbox_undispatched_idx` on `(created_at) where dispatched_at is null` —
--     00 §5.7 P4: the dispatcher's claim query filters exactly this predicate and
--     walks `created_at`, so the index is also the scan order and never includes
--     the rows the mechanism has already moved on (01.5.1 §4).
--
-- Grants (00 §5.4.3 least privilege). 0001's default privileges hand
-- `evidgate_app` DML and `evidgate_operator` SELECT on every table
-- `evidgate_owner` creates in `public`; the explicit revokes below take back what
-- this table does not need:
--   * `evidgate_app`: INSERT only, for T2's `OutboxWriter` inside the tenant
--     transaction. The dispatcher's claim needs `select … for update skip locked`
--     and `update … set dispatched_at`; 01.5.1-T3 is a different task and adds
--     that grant in its own migration (grants are additive, so this is the
--     expand path — it is not granted here because nothing may read or re-stamp
--     a committed outbox row until the dispatcher exists).
--   * `evidgate_operator`: nothing. A mechanism table has no policy, so an
--     operator SELECT would read every org's payloads; the operator's audited
--     read path (TL T76) never touches the outbox.
--   * `evidgate_worker_sched`: nothing. This role only executes the owner
--     `SECURITY DEFINER` sweeps (TL T80), and no sweep owns outbox rows.

create table if not exists public.outbox (
  id uuid not null,
  org_id uuid not null,
  aggregate_type text not null,
  aggregate_id uuid not null,
  task_type text not null,
  payload jsonb not null,
  idempotency_key text not null,
  created_at timestamptz not null default now(),
  dispatched_at timestamptz,
  constraint outbox_pkey primary key (id),
  -- Input limits (00 §5.7 S3, matching 0008's task queue): every field a
  -- producer can fill is bounded, and the payload cap is 64 KiB
  -- (pg_column_size) — an outbox row is a pointer to work, not the work itself.
  constraint outbox_aggregate_type_length_check check (char_length(aggregate_type) between 1 and 128),
  constraint outbox_task_type_length_check check (char_length(task_type) between 1 and 128),
  constraint outbox_idempotency_key_length_check check (char_length(idempotency_key) between 1 and 256),
  constraint outbox_payload_size_check check (pg_column_size(payload) <= 65536)
);

create unique index if not exists outbox_org_id_uq on public.outbox (org_id, id);
create unique index if not exists outbox_org_idem_uq on public.outbox (org_id, idempotency_key);
create index if not exists outbox_undispatched_idx on public.outbox (created_at) where dispatched_at is null;

grant insert on public.outbox to evidgate_app;
revoke select, update, delete on public.outbox from evidgate_app;
revoke all on public.outbox from evidgate_operator;
revoke all on public.outbox from evidgate_worker_sched;
