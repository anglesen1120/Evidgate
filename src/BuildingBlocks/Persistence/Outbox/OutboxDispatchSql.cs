namespace Evidgate.BuildingBlocks.Persistence.Outbox;

/// <summary>
/// The dispatcher's statements (01.5.1-T3.1). They live in one place for the same
/// reason <c>TaskQueueSql</c> does: more than one component issues them (the
/// dispatcher and its gauge callback), and the suite asserts on the very text
/// production runs — <c>Dispatcher_BatchIsOneRoundTrip</c> counts these
/// statements per batch — rather than on a copy that could drift.
/// </summary>
/// <remarks>
/// One batch is exactly three data statements in one transaction: a batch claim,
/// one <c>insert … select</c> over the outbox rows that claim locked, and one
/// update that stamps them. The number of statements is constant in the batch
/// size — the 00 §5.7 P2 contract ("the dispatcher inserts task rows as one
/// INSERT … SELECT batch") — so a round of work never costs a statement per row.
/// </remarks>
public static class OutboxDispatchSql
{
    /// <summary>
    /// Batch-claims the oldest undispatched rows, walking
    /// <c>outbox_undispatched_idx</c> (partial on <c>dispatched_at is null</c>,
    /// ordered by <c>created_at</c>, so the predicate and the order are the same
    /// index — 00 §5.7 P4). The <c>id</c> tiebreak keeps a batch of rows sharing
    /// one timestamp in the FIFO order their UUIDv7 ids already encode.
    /// <c>for update skip locked</c> is the concurrency contract: two dispatchers
    /// (or a dispatch plus an operator read) never wait on each other — the second
    /// walks past the locked rows instead. The row is locked until the batch's
    /// transaction commits or rolls back, which is what makes a mid-batch crash
    /// safe: the lock and the stamp are the same unit of work.
    /// </summary>
    /// <remarks>
    /// Only <c>id</c> is selected: the batch re-reads the locked rows inside the
    /// same transaction when it builds the task rows, so the claim moves the
    /// minimum it can and the insert gets the authoritative payload.
    /// </remarks>
    public const string ClaimUndispatched = """
        select id
          from public.outbox
         where dispatched_at is null
         order by created_at, id
         limit @batch
         for update skip locked
        """;

    /// <summary>
    /// One <c>insert … select</c> for the whole claimed batch (00 §5.7 P2): the
    /// select re-reads the outbox rows — which this transaction still holds a
    /// <c>for update</c> lock on, so they cannot change under it — and builds one
    /// <c>task</c> row each. The task id is generated by the application as a
    /// UUIDv7 (00 §7, same convention as <c>TaskQueueWriter</c>: the ids the
    /// worker produces are ordered by write time without a database sequence),
    /// passed as a positional pair with the claimed outbox id through a single
    /// <c>unnest</c> so the parameter list is two arrays, not two columns of
    /// literals.
    /// </summary>
    /// <remarks>
    /// <c>'outbox:' || outbox.id</c> is the task idempotency key (01.5.1 §7), so
    /// <c>on conflict do nothing</c> on <c>task_idem_uq</c> makes a second
    /// dispatch attempt of the same row a silent no-op — the at-least-once A10
    /// posture — instead of a 23505 the dispatcher would have to interpret.
    /// Queue: a task_type carries no queue of its own — a consumer claims any
    /// registered type on every queue it polls — so routing is a deployment
    /// decision (<see cref="Tasks.TasksOptions.QueueRoutes"/>), resolved in the
    /// same statement by the <c>left join unnest(@route_task_types,
    /// @route_queues)</c> parameter pair and falling back to
    /// <see cref="Tasks.TasksOptions.DispatchDefaultQueue"/> for a type the
    /// deployment has not routed (01.5.1 §11: an unrouted type stays
    /// <c>queued</c>, never lost).
    /// </remarks>
    public const string EnqueueTasks = """
        insert into public.task
          (id, org_id, queue, task_type, payload, idempotency_key, available_at)
        select g.task_id,
               o.org_id,
               coalesce(r.queue, @default_queue),
               o.task_type,
               o.payload,
               'outbox:' || o.id::text,
               now()
          from unnest(@outbox_ids::uuid[], @task_ids::uuid[]) as g(outbox_id, task_id)
          join public.outbox o
            on o.id = g.outbox_id
          left join unnest(@route_task_types::text[], @route_queues::text[]) as r(task_type, queue)
            on r.task_type = o.task_type
         on conflict do nothing
         returning id as "Id"
        """;

    /// <summary>
    /// Stamps the claimed rows dispatched. <c>dispatched_at is null</c> is kept
    /// as a redundant predicate — the claim's locks already make a concurrent
    /// stamper impossible, but the predicate documents that the stamp is exactly
    /// once per row and makes the EPQ re-check a no-op for an out-of-transaction
    /// writer that never got a lock.
    /// </summary>
    /// <remarks>
    /// The <c>returning</c> clause gives the batch the per-row dispatch lag —
    /// <c>now() - created_at</c>, the time the work waited between the business
    /// commit and the queue insert — recorded into
    /// <c>task_dispatch_lag_seconds</c> (01.5.1 §7, 00 §11 SLI) after the
    /// transaction commits, so only work that actually dispatched is measured.
    /// </remarks>
    public const string MarkDispatched = """
        update public.outbox
           set dispatched_at = now()
         where id = any(@outbox_ids::uuid[])
           and dispatched_at is null
        returning extract(epoch from (now() - created_at))::double precision as "LagSeconds"
        """;

    /// <summary>
    /// The backlog depth behind <c>outbox_undispatched</c> (01.5.1 §7 gauge): a
    /// bounded walk over <c>outbox_undispatched_idx</c>'s predicate — the
    /// dispatcher's own signal of "how much work the queue has not seen yet".
    /// The count saturates at <see cref="UndispatchedGaugeCap"/>: an exact count
    /// is a sequential index scan linear in the backlog, so a metrics callback
    /// that runs every export interval must not read an unbounded row range
    /// (perf review wave 5: 34.6 ms seq-scan plan measured at a 600k-row
    /// backlog before vacuum; the cap keeps the hot path index-only and O(cap)).
    /// </summary>
    public const string CountUndispatched = """
        select count(*) from (
          select id from public.outbox
          where dispatched_at is null
          limit @gauge_cap) capped
        """;

    /// <summary>Backlog cap for <see cref="CountUndispatched"/>; above it the gauge reports the cap.</summary>
    public const int UndispatchedGaugeCap = 100_000;
}
