namespace Evidgate.Modules.Tenancy.Domain;

/// <summary>
/// Write model of <c>public.organization</c> (02.1.1-T1.3, feature plan §4).
/// The organization is the tenant root and the documented business-table
/// exception without an <c>org_id</c> column (00 §5.4.1, TL T4): its own
/// <c>id</c> is what the RLS policy compares to <c>evidgate.current_org_id()</c>.
/// The mapping is
/// <see cref="Infrastructure.Persistence.OrganizationConfiguration"/>; the
/// commands and the status transitions that fill this state are 02.1.1-T2's, and
/// the quota/limit columns are 02.1.1-T3's (they are not part of this write
/// model).
/// </summary>
internal sealed class Organization
{
    /// <summary>UUIDv7 generated by the application, never by the database (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>Display name, ≤ 128 chars (input limit, 00 §5.7 S3).</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>Globally unique onboarding key; <c>^[a-z0-9][a-z0-9-]{0,61}[a-z0-9]$</c> (D-A1, 0012).</summary>
    public string Slug { get; set; } = string.Empty;

    /// <summary>One of <see cref="TenancyStatus"/>.</summary>
    public string Status { get; set; } = TenancyStatus.Active;

    /// <summary>Default retention for the org's projects; null means "no default" (plan 12 consumes it).</summary>
    public int? RetentionDefaultDays { get; set; }

    /// <summary>Optional Google Workspace email-domain allowlist (FR-02-3).</summary>
    public string[]? AllowedEmailDomains { get; set; }

    /// <summary>Row creation, UTC (00 §5.4.4).</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Last write, UTC; the commands set it on every mutation.</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic concurrency token (00 §7, 00 §5.5 C4); starts at 1.</summary>
    public int Version { get; set; } = 1;

    /// <summary>Projects the org may hold that are not <c>deleted</c>; null = no limit (02.1.1-T3, 0013).</summary>
    public int? MaxProjects { get; set; }

    /// <summary>Active memberships the org may hold; null = no limit (02.1.1-T3, enforced by plan 12).</summary>
    public int? MaxSeats { get; set; }

    /// <summary>
    /// AC8's opt-in (02.1.2 §4, migration 0043): email-only auto-bind of a pending invite is
    /// allowed only for an org that set this, and only for the provider-verified domain of the
    /// signed-in address. Off by default, so no existing org silently opts in.
    /// </summary>
    public bool InviteAutobindVerifiedDomain { get; set; }
}
