namespace Evidgate.Modules.Tenancy.Domain;

/// <summary>
/// Write model of <c>public.project</c> (02.1.1-T1.3, feature plan §4). Every
/// business row below an organization hangs off <c>(org_id, id)</c>, so the
/// project carries both keys: <c>Id</c> is the globally unique UUIDv7 the API
/// addresses (<c>/v1/projects/{p}</c>) and <c>OrgId</c> is the tenant key the RLS
/// policy filters on. The mapping is
/// <see cref="Infrastructure.Persistence.ProjectConfiguration"/>; the commands
/// and the <c>project_scope_mismatch</c> guard are 02.1.1-T2's,
/// <c>DefaultEnvironmentId</c>'s composite FK is 05.1.2-T1's, and
/// <c>retention_days</c>/<c>monthly_run_quota</c> are 02.1.1-T3's (neither is
/// part of this write model).
/// </summary>
internal sealed class Project
{
    /// <summary>UUIDv7 generated by the application, never by the database (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>Owning organization; composite tenant key <c>(org_id, id)</c>.</summary>
    public Guid OrgId { get; set; }

    /// <summary>Display name, ≤ 128 chars (input limit, 00 §5.7 S3).</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>Onboarding key, unique per org (<c>unique (org_id, slug)</c> → 409 <c>slug_taken</c>).</summary>
    public string Slug { get; set; } = string.Empty;

    /// <summary>One of <see cref="TenancyStatus"/>.</summary>
    public string Status { get; set; } = TenancyStatus.Active;

    /// <summary>Preferred environment for new runs; 05.1.2-T1 adds the composite FK to <c>environment</c>.</summary>
    public Guid? DefaultEnvironmentId { get; set; }

    /// <summary>Row creation, UTC (00 §5.4.4).</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Last write, UTC; the commands set it on every mutation.</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic concurrency token (00 §7, 00 §5.5 C4); starts at 1.</summary>
    public int Version { get; set; } = 1;
}
