namespace Evidgate.Modules.Identity.Domain;

/// <summary>
/// Write model of <c>public.membership_role</c> (02.1.2-T1.2, feature plan §4): one
/// role granted to one membership. The mapping is
/// <see cref="Infrastructure.Persistence.MembershipRoleConfiguration"/>.
/// </summary>
/// <remarks>
/// <see cref="RoleId"/> references <c>role.id</c> <em>by value</em>: the built-in
/// roles of 0010 carry <c>org_id IS NULL</c>, so the composite tenant key
/// <c>(org_id, role_id) → role (org_id, id)</c> the feature plan §4 asks for could
/// never match one, and a single-column key is refused by the 02.9.1-T2 composite-FK
/// gate for every tenant table. The reference is therefore validated in the command
/// (<c>GrantRoleCommand</c> resolves the role under RLS and answers 409
/// <c>unknown_role</c>); the migration's header records the full reasoning.
/// </remarks>
internal sealed class MembershipRole
{
    /// <summary>UUIDv7 generated by the application, never by the database (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>The tenant of the parent membership (RLS scope, 00 §5.4.1).</summary>
    public Guid OrgId { get; set; }

    /// <summary>The membership this role is granted to.</summary>
    public Guid MembershipId { get; set; }

    /// <summary>The granted role — a built-in catalogue role or the org's own (<see cref="MembershipRole"/> remarks).</summary>
    public Guid RoleId { get; set; }

    /// <summary>The member who granted the role, when a member principal granted it.</summary>
    public Guid? GrantedBy { get; set; }

    /// <summary>When the grant happened; the column default applies on insert.</summary>
    public DateTimeOffset GrantedAt { get; set; }

    /// <summary>Row creation, UTC (00 §5.4.4); the column default applies on insert.</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Last write, UTC — set by <c>set_updated_at_and_version</c> on update (0011).</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic concurrency token (00 §7, §5.5 C4); the trigger increments it.</summary>
    public int Version { get; set; } = 1;
}
