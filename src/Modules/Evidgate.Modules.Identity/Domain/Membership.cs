using Evidgate.Modules.Identity.Contracts;

namespace Evidgate.Modules.Identity.Domain;

/// <summary>
/// Write model of <c>public.membership</c> (02.1.2-T1.2, feature plan §4): the row
/// that makes a user a member of one org. The mapping is
/// <see cref="Infrastructure.Persistence.MembershipConfiguration"/>; the read side is
/// Dapper (<c>MembershipReadSql</c>), because 00 §5.5 C5 keeps reads on the SQL path
/// and C4 keeps writes on this one.
/// </summary>
/// <remarks>
/// <see cref="InvitedEmail"/> is personal data (02.1.2 §8): it is stored normalised
/// (the migration's check constraint refuses a non-normalised value) and never
/// logged. The token columns (<see cref="InviteSecretPrefix"/>,
/// <see cref="InviteTokenHash"/>, <see cref="InvitePepperVersion"/>,
/// <see cref="InviteExpiresAt"/>) are minted by 02.1.2-T2's create/resend commands
/// (T75) and are set all together or not at all (migration 0043's
/// <c>membership_invite_token_all_or_none</c>). A pending row with those columns
/// unset is a complete row, not a placeholder.
/// </remarks>
internal sealed class Membership
{
    /// <summary>UUIDv7 generated by the application, never by the database (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>The tenant this membership belongs to (RLS scope, 00 §5.4.1).</summary>
    public Guid OrgId { get; set; }

    /// <summary>The bound user, or null while the invite is <c>pending</c> (filled at bind, 02.3.1-T2).</summary>
    public Guid? UserId { get; set; }

    /// <summary>The normalised invite address (trimmed, lowercased) — never an identity key (FR-02-4).</summary>
    public string InvitedEmail { get; set; } = string.Empty;

    /// <summary>One of <see cref="MembershipStatus"/>.</summary>
    public string Status { get; set; } = MembershipStatus.Pending;

    /// <summary>The user who issued the invite, when a member principal issued it.</summary>
    public Guid? InvitedBy { get; set; }

    /// <summary>The public lookup key of <c>evidgate_resolve.invite_by_secret</c> (T75); null until 02.1.2-T2.</summary>
    public string? InviteSecretPrefix { get; set; }

    /// <summary>HMAC-SHA256 of the invite link secret (T5 pattern); null until 02.1.2-T2.</summary>
    public byte[]? InviteTokenHash { get; set; }

    /// <summary>
    /// The pepper version the <see cref="InviteTokenHash"/> was computed under (T5, migration
    /// 0043's <c>membership_invite_token_all_or_none</c>): a rotation keeps the old pepper
    /// alive while its invites drain, exactly as <c>session.pepper_version</c> does (0042).
    /// Null when no token was minted.
    /// </summary>
    public int? InvitePepperVersion { get; set; }

    /// <summary>When the pending invite stops being bindable (02.1.2 §6); null until 02.1.2-T2.</summary>
    public DateTimeOffset? InviteExpiresAt { get; set; }

    /// <summary>Row creation, UTC (00 §5.4.4); the column default applies on insert.</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Last write, UTC — set by <c>set_updated_at_and_version</c> on update (0011).</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic concurrency token (00 §7, §5.5 C4); the trigger increments it.</summary>
    public int Version { get; set; } = 1;

    /// <summary>True when the membership currently grants access (an active member).</summary>
    public bool IsActive => string.Equals(Status, MembershipStatus.Active, StringComparison.Ordinal);

    /// <summary>
    /// The admin removal/disable transition of 02.1.2 §6 (<c>active → removed</c>).
    /// Terminal: a removed membership is never reactivated — a re-invite is a new row.
    /// </summary>
    public void Remove() => Status = MembershipStatus.Removed;
}
