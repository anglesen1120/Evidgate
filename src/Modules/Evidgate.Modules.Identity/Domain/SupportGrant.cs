namespace Evidgate.Modules.Identity.Domain;

/// <summary>
/// Write model of <c>public.support_grant</c>: the operator's request for tenant-scoped access and the two
/// transitions a tenant makes on it. A grant is filed <c>requested</c>; approval and revocation are updates, both
/// write-once, and <c>expired</c> is derived at read time rather than stored so no sweeper has to cut access.
/// The mapping is <see cref="Infrastructure.Persistence.SupportGrantConfiguration"/>; the list is the Dapper read
/// path, as 00 §5.5 C5 keeps reads on the SQL side.
/// </summary>
internal sealed class SupportGrant
{
    /// <summary>UUIDv7 generated by the application, never by the database (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>The tenant whose data the grant opens (RLS scope, 00 §5.4.1).</summary>
    public Guid OrgId { get; set; }

    /// <summary>The operator account the access belongs to; never a member of the org.</summary>
    public Guid OperatorUserId { get; set; }

    /// <summary>The permission strings the grant covers, <c>resource:action</c>.</summary>
    public string[] Scopes { get; set; } = [];

    /// <summary>The projects the scopes cover; empty means the whole org.</summary>
    public Guid[] ProjectIds { get; set; } = [];

    /// <summary>Why the operator asks for the access; 1..1000 characters.</summary>
    public string Reason { get; set; } = string.Empty;

    /// <summary>The approving member's user id, or null while requested.</summary>
    public Guid? ApprovedBy { get; set; }

    /// <summary>The approval instant recorded by the database, or null while requested.</summary>
    public DateTimeOffset? ApprovedAt { get; set; }

    /// <summary>When the access stops, at most 72 hours after the request.</summary>
    public DateTimeOffset ExpiresAt { get; set; }

    /// <summary>The revocation instant, or null while live.</summary>
    public DateTimeOffset? RevokedAt { get; set; }

    /// <summary>Row creation, UTC (00 §5.4.4).</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Last write, UTC — set by <c>set_updated_at_and_version</c> on update.</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic concurrency token (00 §7); the trigger increments it.</summary>
    public int Version { get; set; } = 1;

    /// <summary>True while the grant is filed, unrevoked and unexpired — the only state approval may leave.</summary>
    /// <param name="now">The request's clock.</param>
    public bool IsApprovableAt(DateTimeOffset now) =>
        ApprovedAt is null && RevokedAt is null && ExpiresAt > now;

    /// <summary>
    /// Records the approval. The database overwrites the instant with the server's clock; the write carries only
    /// the approver and a placeholder instant, clamped to the row's creation so a caller clock behind the database
    /// cannot trip the table's <c>support_grant_approved_after_created_check</c>.
    /// </summary>
    /// <param name="approverId">The authenticated member approving; never the requester.</param>
    /// <param name="now">The request's clock.</param>
    public void Approve(Guid approverId, DateTimeOffset now)
    {
        if (ApprovedAt is not null || RevokedAt is not null)
        {
            throw new InvalidOperationException($"support grant {Id} is not awaiting approval");
        }

        ApprovedBy = approverId;
        ApprovedAt = now >= CreatedAt ? now : CreatedAt;
    }

    /// <summary>Records the revocation; a revoked grant accepts no further change.</summary>
    /// <param name="now">The request's clock.</param>
    public void Revoke(DateTimeOffset now)
    {
        if (RevokedAt is not null)
        {
            throw new InvalidOperationException($"support grant {Id} is already revoked");
        }

        RevokedAt = now >= CreatedAt ? now : CreatedAt;
    }
}
