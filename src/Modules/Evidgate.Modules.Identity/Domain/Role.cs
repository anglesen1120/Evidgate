namespace Evidgate.Modules.Identity.Domain;

/// <summary>
/// Write model of <c>public.role</c> (02.2.1-T2.2, 02 §4.1). A role is data, not
/// code (D2): the nine built-in roles of 00 §2 are catalogue rows with
/// <c>org_id is null</c> and <see cref="IsBuiltin"/> true, and a custom role is an
/// ordinary org row (<c>org_id</c> set, <see cref="IsBuiltin"/> false) created by
/// the flagged command of 02.2.1 §5. The mapping is
/// <see cref="Infrastructure.Persistence.RoleConfiguration"/>; the read side is
/// Dapper (<c>IdentityReadSql.RolesPage</c>), because 00 §5.5 C5 keeps reads on the
/// SQL path and C4 keeps writes on this one.
/// </summary>
internal sealed class Role
{
    /// <summary>UUIDv7 generated by the application, never by the database (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>Null for a built-in catalogue role, the owning org for a custom role (02 §4.5).</summary>
    public Guid? OrgId { get; set; }

    /// <summary>Role code, <c>^[a-z][a-z0-9_]*$</c>; unique per org, and globally unique for built-ins.</summary>
    public string Code { get; set; } = string.Empty;

    /// <summary>Display name, 1..64 chars (input limit, 00 §5.7 S3).</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>True for a catalogue role: immutable (AC6), and it may never carry an <c>org_id</c>.</summary>
    public bool IsBuiltin { get; set; }

    /// <summary>
    /// Who may hold the role (W7-SEC-03, 0010's <c>role_kind_check</c>): one of
    /// <see cref="RoleKind"/>. A custom role is always <see cref="RoleKind.Member"/> —
    /// custom roles are member roles (02.2.1 §5) — while the seeded
    /// <c>ci_producer</c>/<c>agent</c> are <c>service</c> and the two staff roles are
    /// <c>staff</c>, so no membership can hold one.
    /// </summary>
    public string Kind { get; set; } = RoleKind.Member;

    /// <summary>Row creation, UTC (00 §5.4.4); the column default applies on insert.</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Last write, UTC — set by <c>set_updated_at_and_version</c> on update (0010).</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic concurrency token (00 §7, 00 §5.5 C4); the trigger increments it.</summary>
    public int Version { get; set; } = 1;
}
