namespace Evidgate.Modules.Identity.Domain;

/// <summary>
/// Write model of <c>public.role_permission</c> (02.2.1-T2.2, 02 §4.1): the grant of
/// one 00 §2 permission code to one role. Built-in grant rows carry
/// <c>org_id is null</c> like their role (platform catalogue rows, written only by
/// <c>evidgate_owner</c>); a custom role's grants are org rows, which is why
/// <see cref="OrgId"/> is nullable here even though every row the flagged commands
/// write has it set — the mapping mirrors the migrated column instead of narrowing
/// it. The mapping is
/// <see cref="Infrastructure.Persistence.RolePermissionConfiguration"/>.
/// </summary>
internal sealed class RolePermission
{
    /// <summary>UUIDv7 generated by the application, never by the database (00 §7).</summary>
    public Guid Id { get; set; }

    /// <summary>Null for a built-in role's grant, the owning org for a custom role's grant.</summary>
    public Guid? OrgId { get; set; }

    /// <summary>The granted role; a single-column reference because a built-in role has no <c>org_id</c> (0010).</summary>
    public Guid RoleId { get; set; }

    /// <summary>The granted catalogue code; the foreign key is <c>permission.code</c> (0010).</summary>
    public string PermissionCode { get; set; } = string.Empty;

    /// <summary>Row creation, UTC (00 §5.4.4); the column default applies on insert.</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Last write, UTC — set by <c>set_updated_at_and_version</c> on update (0010).</summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Optimistic concurrency token (00 §7, 00 §5.5 C4); the trigger increments it.</summary>
    public int Version { get; set; } = 1;
}
