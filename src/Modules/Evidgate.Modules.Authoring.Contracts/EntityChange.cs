using System.Text.Json;

namespace Evidgate.Modules.Authoring.Contracts;

/// <summary>
/// One change of one authoring entity, as a caller describes it to <see cref="IAuthoringVersionWriter"/>
/// (13.1.1 §5). A caller never assembles an <c>authoring_version</c> row by hand: the writer owns
/// <c>version_no</c>, <c>content_hash</c>, the <c>created_at</c> stamp and — for a <see cref="AuthoringChangeKind.SoftDelete"/>
/// — the non-empty guard of AC7.
/// </summary>
/// <param name="EntityKind">Which of the three entities is changing.</param>
/// <param name="ChangeKind">Create, update or soft delete.</param>
/// <param name="EntityId">The entity's id; generated by the caller with <c>Guid.CreateVersion7()</c> for a create.</param>
/// <param name="Content">
/// The entity's full user-visible state for a create or an update (13.1.1 §4: <c>feature_node</c> →
/// <c>{kind, title, position, parent_id}</c>, <c>checklist_item</c> → <c>{feature_node_id, title, description, priority,
/// state, position}</c>, <c>manual_test_case</c> → <c>{checklist_item_id, code, title, description, precondition, steps,
/// priority, state}</c>) — the exact member set, no server field. Unused for a soft delete.
/// </param>
/// <param name="Reason">An optional 1..500 character reason recorded on the version row (13.1.2's bounded reasons).</param>
public sealed record EntityChange(
    AuthoringEntityKind EntityKind,
    AuthoringChangeKind ChangeKind,
    Guid EntityId,
    JsonElement Content,
    string? Reason = null)
{
    /// <summary>A new entity (13.1.1 AC1/AC3/AC4); the writer inserts the row and <c>version_no = 1</c>.</summary>
    /// <param name="entityKind">The entity kind.</param>
    /// <param name="entityId">The id the caller generated.</param>
    /// <param name="content">The full snapshot of the new entity.</param>
    public static EntityChange Create(AuthoringEntityKind entityKind, Guid entityId, JsonElement content) =>
        new(entityKind, AuthoringChangeKind.Create, entityId, content);

    /// <summary>A changed entity (13.1.1 AC5); the writer appends the next version and writes the new snapshot.</summary>
    /// <param name="entityKind">The entity kind.</param>
    /// <param name="entityId">The entity.</param>
    /// <param name="content">The full new snapshot; a snapshot equal to the last one is the AC5 no-op.</param>
    public static EntityChange Update(AuthoringEntityKind entityKind, Guid entityId, JsonElement content) =>
        new(entityKind, AuthoringChangeKind.Update, entityId, content);

    /// <summary>A soft delete (13.1.1 AC7); the writer refuses one whose entity still holds live content.</summary>
    /// <param name="entityKind">The entity kind.</param>
    /// <param name="entityId">The entity.</param>
    /// <param name="reason">An optional 1..500 character reason (13.1.2's <c>merged into …</c> form).</param>
    public static EntityChange SoftDelete(AuthoringEntityKind entityKind, Guid entityId, string? reason = null) =>
        new(entityKind, AuthoringChangeKind.SoftDelete, entityId, default, reason);
}
