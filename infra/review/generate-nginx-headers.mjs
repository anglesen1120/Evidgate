#!/usr/bin/env node
// Generates the nginx snippet that carries the app-origin security headers.
//
// The policy is not copied here: it is built by apps/web/scripts/csp.mjs, the
// module the E2E gate enforces, so the deployed edge and the tested server
// cannot drift apart (U2: one implementation per format). The one thing nginx
// supplies is the nonce, because it is the only component that knows a response
// has started — see the emitted comment for why its own $request_id is a valid
// CSP nonce.
//
// usage: node infra/review/generate-nginx-headers.mjs [--out <file>]
//   EVIDGATE_REVIEW_PUBLIC_ORIGIN  optional https origin appended to connect-src
//                                  (the app calls its own origin, so 'self' is
//                                  already sufficient; the origin is added because
//                                  the app-origin contract lists it)
// Exit: 0 written, 1 invalid input.

import { readFileSync, writeFileSync } from 'node:fs';
import { buildCsp, generateNonce, NONCE_PLACEHOLDER } from '../../apps/web/scripts/csp.mjs';

const USAGE = 'usage: node infra/review/generate-nginx-headers.mjs [--out <file>]\n';

/** The CSP nonce for one response, as nginx spells it. */
const NONCE_VARIABLE = '$request_id';

const APP_CONTRACT = new URL('../../apps/web/scripts/app-origin-csp.json', import.meta.url);

function fail(message) {
  console.error(`generate-nginx-headers: ${message}`);
  process.exit(1);
}

function parseArgs(argv) {
  let out = null;
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--out') {
      out = argv[index + 1];
      if (out === undefined) fail('--out needs a path');
      index += 1;
    } else if (arg === '-h' || arg === '--help') {
      process.stdout.write(USAGE);
      process.exit(0);
    } else {
      fail(`unexpected argument '${arg}' (try --help)`);
    }
  }
  return out;
}

/**
 * The JSON contract is documentation of the same policy; it is read so that a
 * change to one without the other fails here instead of shipping.
 */
function readAppContract() {
  let contract;
  try {
    contract = JSON.parse(readFileSync(APP_CONTRACT, 'utf8'));
  } catch (error) {
    fail(`cannot read ${APP_CONTRACT.pathname}: ${error.message}`);
  }
  if (contract.nonce_placeholder !== NONCE_PLACEHOLDER) {
    fail(
      `${APP_CONTRACT.pathname} placeholder '${contract.nonce_placeholder}' is not the ` +
        `csp.mjs placeholder '${NONCE_PLACEHOLDER}'`,
    );
  }
  const frameAncestors = contract.directives?.['frame-ancestors'];
  if (!Array.isArray(frameAncestors) || !frameAncestors.includes("'none'")) {
    fail(`${APP_CONTRACT.pathname} no longer pins frame-ancestors 'none'`);
  }
  const connectSrc = contract.directives?.['connect-src'];
  if (!Array.isArray(connectSrc) || connectSrc.length !== 1 || connectSrc[0] !== "'self'") {
    fail(
      `${APP_CONTRACT.pathname} connect-src is no longer exactly 'self', so appending the ` +
        'public origin here would silently widen the policy',
    );
  }
  return contract;
}

function buildHeaderValue(publicOrigin) {
  const nonce = generateNonce();
  const connectSrc = publicOrigin === '' ? [] : [publicOrigin];
  // buildCsp validates the origin shape (https/wss only, no path, no wildcard)
  // and refuses to append to a directive it cannot reason about.
  let policy;
  try {
    policy = buildCsp({ nonce, connectSrc });
  } catch (error) {
    fail(error.message);
  }

  const nonceSource = `'nonce-${nonce}'`;
  if (!policy.includes(nonceSource)) {
    fail('the generated policy does not carry the nonce this script generated');
  }
  const value = policy.split(nonceSource).join(`'nonce-${NONCE_VARIABLE}'`);
  if (/["\r\n]/.test(value)) {
    fail('the policy cannot be quoted inside an nginx directive');
  }
  if (value.split(NONCE_VARIABLE).length !== 2) {
    fail(`the policy must name ${NONCE_VARIABLE} exactly once, in style-src`);
  }
  return value;
}

function render(headerValue) {
  return `# Generated by infra/review/generate-nginx-headers.mjs from
# apps/web/scripts/csp.mjs and apps/web/scripts/app-origin-csp.json. Do not edit:
# change the policy there and rebuild the image.
#
# The nonce comes from nginx, not from this file: $request_id is 32 hex
# characters, and hex is a subset of the base64 alphabet a CSP nonce-source
# accepts, so the token is valid and unique per request (128 bits from the
# request id). csp.mjs's own generator emits 22 base64 characters because a
# Node server has to issue the value itself; only the token differs here, the
# policy shape is the one csp.mjs asserts.
add_header Content-Security-Policy "${headerValue}" always;
sub_filter '${NONCE_PLACEHOLDER}' ${NONCE_VARIABLE};
sub_filter_once off;
add_header Strict-Transport-Security "max-age=31536000" always;
add_header X-Content-Type-Options "nosniff" always;
add_header Referrer-Policy "no-referrer" always;
`;
}

const out = parseArgs(process.argv.slice(2));
readAppContract();
const snippet = render(buildHeaderValue((process.env.EVIDGATE_REVIEW_PUBLIC_ORIGIN ?? '').trim()));

if (out === null) {
  process.stdout.write(snippet);
} else {
  try {
    writeFileSync(out, snippet);
  } catch (error) {
    fail(`cannot write ${out}: ${error.message}`);
  }
}
