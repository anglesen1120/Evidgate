#!/usr/bin/env python3
"""Regenerate the generated parts of the plan set from the task graph:

- plans/00-overview.md §14 estimate table + milestone line + calendar numbers
- plans/features/README.md §5.1 waves, §5.2 critical chain, §7 index

Run after any change to a task row (size, version, milestone, Depends on). Idempotent.
"""
import json, re, subprocess, sys
from collections import defaultdict

SIZE = {"XS": .25, "S": .5, "M": 1, "L": 2, "XL": 3}
py = sys.executable
g = json.loads(subprocess.check_output([py, "scripts/plan_graph.py", "--json"]))
T = g["tasks"]

def n(x): return f"{int(x)}" if x == int(x) else f"{x:g}"

# ---- 00 §14 -------------------------------------------------------------------
per = defaultdict(lambda: defaultdict(float)); cnt = defaultdict(int); ms = defaultdict(float)
for t, d in T.items():
    f = d["file"].split("/")[1]
    per[f][d["ver"]] += SIZE[d["size"]]; cnt[f] += 1; ms[d["ms"]] += SIZE[d["size"]]
rows, tot = [], defaultdict(float)
for f in sorted(per):
    v = per[f]; r = sum(v.values())
    for k in ("V1", "V2", "V3"): tot[k] += v[k]
    rows.append(f"| `{f}` | {cnt[f]} | {n(v['V1'])} | {n(v['V2'])} | {n(v['V3'])} | {n(r)} | {r * 1.2:.1f} |")
R = sum(tot.values())
rows.append(f"| **Total** | **{sum(cnt.values())}** | **{n(tot['V1'])}** | **{n(tot['V2'])}** | **{n(tot['V3'])}** | **{n(R)}** | **{R * 1.2:.1f}** |")
rows.append(f"| Buffered (× 1.2) | | {tot['V1'] * 1.2:.1f} | {tot['V2'] * 1.2:.1f} | {tot['V3'] * 1.2:.1f} | | |")
p = "plans/00-overview.md"; s = open(p, encoding="utf-8").read()
head = "| Plan | Tasks | V1 | V2 | V3 | Total raw | Total buffered |\n|---|---|---|---|---|---|---|\n"
a = s.index(head); b = s.index("\n\n", a)
s = s[:a] + head + "\n".join(rows) + s[b:]
s = re.sub(r"By milestone \(raw\): [^\n]*?\. Every V1 task", "By milestone (raw): " + " · ".join(f"{k} {n(ms[k])}" for k in sorted(ms)) + ". Every V1 task", s, count=1)
v1b, v2b = tot["V1"] * 1.2, tot["V2"] * 1.2
s = re.sub(r"buffered V1 is [\d.]+ person-days \(499\.8 before CR-D-1 and the TL review\)\. At 5 working days per week and full parallelism, that is ≈ [\d.]+ weeks for 2 engineers and ≈ [\d.]+ weeks for 3,",
           f"buffered V1 is {v1b:.1f} person-days (499.8 before CR-D-1 and the TL review). At 5 working days per week and full parallelism, that is ≈ {v1b / 10:.1f} weeks for 2 engineers and ≈ {v1b / 15:.1f} weeks for 3,", s, count=1)
s = re.sub(r"V2 buffered \([\d.]+ d\) is ≈ [\d.]+ / [\d.]+ weeks", f"V2 buffered ({v2b:.1f} d) is ≈ {v2b / 10:.1f} / {v2b / 15:.1f} weeks", s, count=1)
open(p, "w", encoding="utf-8").write(s)

# ---- README §5.1, §5.2, §7 --------------------------------------------------------
def out(*args): return subprocess.check_output([py, "scripts/feature_index.py", *args]).decode().strip()
p = "plans/features/README.md"; s = open(p, encoding="utf-8").read()
def put(start, end, body):
    global s
    a = s.index(start) + len(start); b = s.index(end, a)
    s = s[:a] + body + s[b:]
put("### 5.1 Waves per milestone\n\n", "\n\n### 5.2", out("--order"))
put("### 5.2 Critical chain (task level)\n\n", "\n\nReading [INFERENCE]", out("--critical"))
put("### 5.3 Bundles (build together, ordered by task)\n\n", "\n\n### 5.4", out("--bundles"))
idx = out("--index")
a = s.index("## 7. Index\n") + len("## 7. Index\n")
s = s[:a] + "\nGenerated by `scripts/regen_docs.py`; one row per story. Check with `scripts/check_features.py` (structure, sub-task sums, ids, header sync).\n\n" + idx + "\n"
open(p, "w", encoding="utf-8").write(s)
print(f"00 §14: {sum(cnt.values())} tasks, {n(R)} raw, {R * 1.2:.1f} buffered; README §5/§7 regenerated ({idx.count(chr(10)) - 1} index rows)")
