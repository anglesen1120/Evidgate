#!/usr/bin/env python3
"""02.2.1-T1.1: generate the C# permission constants from contracts/permissions.json.

The catalogue is the single source of every `resource:action` string (00 §2, 02 D2),
so the C# side must never be hand-written: this script renders
`src/BuildingBlocks/SharedKernel/Authorization/Permissions.g.cs` deterministically —
same input, same bytes — and `scripts/check-permissions-drift.sh` fails CI when the
committed file lags the JSON.

Why SharedKernel: every module references it (00 §5.5), so `Permissions.Run.Create`
is usable from any module without a module-to-module reference, and the type sits
beside `PermissionAttribute`, the contract the pipeline reads. The generated file is
a committed build product; never edit it by hand.

Usage: python3 scripts/generate-permissions.py [--check]
  (no flag)  rewrite the generated file
  --check    exit 1 when the file on disk differs from what would be generated
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / "contracts" / "permissions.json"
OUTPUT = ROOT / "src" / "BuildingBlocks" / "SharedKernel" / "Authorization" / "Permissions.g.cs"

HEADER = """// <auto-generated />
//
// Generated by scripts/generate-permissions.py from contracts/permissions.json — DO NOT EDIT.
// Regenerate with `python3 scripts/generate-permissions.py`; `scripts/check-permissions-drift.sh`
// fails when this file lags the catalogue (02.2.1-T1.1).
//
// One nested class per resource, one const per action, so `Permissions.Run.Create`
// reads as the string it is and a typo cannot compile. `All` and `IsKnown` are what
// the service-principal path needs (00 §5.5 C2: a claim outside the catalogue is
// denied); `TokenDenied` is the expanded deny set an automation token is filtered
// against, so no token can hold an administrative code.

#nullable enable

namespace Evidgate.BuildingBlocks.SharedKernel.Authorization;

/// <summary>
/// Every permission string of <c>contracts/permissions.json</c> as a compile-time
/// constant (00 §2). The catalogue is the single source: a string used in code but
/// absent from the JSON fails the drift gate, and the JSON is what migration 0010
/// seeds into <c>public.permission</c>.
/// </summary>
public static class Permissions
{
"""

FOOTER_TEMPLATE = """
    /// <summary>
    /// Every catalogue code, in ordinal order — the set a service principal's token
    /// claims must be a subset of (a claim outside the catalogue is denied).
    /// </summary>
    public static IReadOnlyList<string> All {{ get; }} =
    [
{all_rows}
    ];

    /// <summary>
    /// The catalogue codes an automation token can never hold, in ordinal order:
    /// <c>token_denied</c> with every <c>resource:*</c> wildcard expanded. A token's
    /// stored permission subset is filtered against this set at creation and at use,
    /// so a catalogue edit that adds an administrative code tightens every token.
    /// </summary>
    public static IReadOnlySet<string> TokenDenied {{ get; }} =
        new HashSet<string>(StringComparer.Ordinal)
        {{
{denied_rows}
        }};

    /// <summary>True when <paramref name="code"/> is a code this catalogue declares.</summary>
    public static bool IsKnown(string? code) => code is not null && Known.Contains(code);

    private static readonly HashSet<string> Known = new(StringComparer.Ordinal)
    {{
{known_rows}
    }};
}}
"""


def pascal(name: str) -> str:
    """snake_case → PascalCase, the identifier spelling of a resource or action."""
    return "".join(part.capitalize() for part in name.split("_") if part)


def xml_escape(text: str) -> str:
    """Escape the five XML entities so a description can never break the doc comment."""
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def wrap(text: str, indent: str, width: int = 116) -> list[str]:
    """Greedy word wrap for a doc comment, one `indent + '/// '` line per output line."""
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if current and len(indent) + 4 + len(candidate) > width:
            lines.append(f"{indent}/// {current}")
            current = word
        else:
            current = candidate
    if current:
        lines.append(f"{indent}/// {current}")
    return lines


def expand_denied(catalogue: dict) -> list[str]:
    """The `token_denied` set with every `resource:*` wildcard expanded, ordinal order.

    An entry that is not a catalogue code (or a wildcard matching none) is a typo, and
    a silently smaller deny set is a fail-open, so generation stops instead.
    """
    codes = {entry["code"] for entry in catalogue["permissions"]}
    expanded: set[str] = set()
    for entry in catalogue["token_denied"]:
        if entry.endswith(":*"):
            matched = {code for code in codes if code.startswith(entry[:-1])}
            if not matched:
                raise SystemExit(
                    f"generate-permissions: token_denied entry {entry!r} matches no catalogue code"
                )
            expanded |= matched
        elif entry in codes:
            expanded.add(entry)
        else:
            raise SystemExit(
                f"generate-permissions: token_denied entry {entry!r} is not in the catalogue"
            )
    return sorted(expanded)


def render(catalogue: dict) -> str:
    permissions = sorted(catalogue["permissions"], key=lambda entry: entry["code"])
    by_resource: dict[str, list[dict]] = {}
    for entry in permissions:
        by_resource.setdefault(entry["resource"], []).append(entry)

    chunks = [HEADER]
    for resource in sorted(by_resource):
        chunks.append(f"    /// <summary>The <c>{resource}</c> resource.</summary>\n")
        chunks.append(f"    public static class {pascal(resource)}\n    {{\n")
        for entry in sorted(by_resource[resource], key=lambda e: e["code"]):
            summary = f"{entry['code']} — {entry['description']}"
            chunks.append("\n".join(wrap(xml_escape(summary), "        ")) + "\n")
            chunks.append(f"        public const string {pascal(entry['action'])} = \"{entry['code']}\";\n")
        chunks.append("    }\n\n")

    all_rows = ",\n".join(f'        "{entry["code"]}"' for entry in permissions)
    known_rows = ",\n".join(f'        "{entry["code"]}"' for entry in permissions)
    denied_rows = ",\n".join(f'            "{code}"' for code in expand_denied(catalogue))
    chunks.append(
        FOOTER_TEMPLATE.format(all_rows=all_rows, known_rows=known_rows, denied_rows=denied_rows)
    )
    return "".join(chunks)


def main(argv: list[str]) -> int:
    catalogue = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    generated = render(catalogue)

    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            print(
                f"generate-permissions: {OUTPUT.relative_to(ROOT)} is stale — "
                "run python3 scripts/generate-permissions.py and commit the result",
                file=sys.stderr,
            )
            return 1
        print(f"generate-permissions: {OUTPUT.relative_to(ROOT)} matches contracts/permissions.json")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(generated)
    print(
        f"generate-permissions: wrote {OUTPUT.relative_to(ROOT)} "
        f"({len(catalogue['permissions'])} permissions, {len(catalogue['roles'])} roles)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
