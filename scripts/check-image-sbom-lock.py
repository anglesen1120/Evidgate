#!/usr/bin/env python3
"""AC3 (10.2.1-T1.3): a per-image CycloneDX SBOM must describe exactly the NuGet
graph the committed lock files resolve.

The SBOM is generated by `dotnet-CycloneDX` over the entry-point project
(scripts/sbom.sh); this checker is the other half of the gate: it fails when the
SBOM and the lock files disagree, which is what a stale SBOM (generated before a
package bump, or from a partial restore) looks like.

The comparison is deliberately narrow and strict:

1. every `pkg:nuget/<id>@<version>` component in the SBOM must exist with the
   same version in the lock file of some project in the entry point's
   ProjectReference closure (the graph the image publishes);
2. every direct dependency pinned in Directory.Packages.props must appear in the
   SBOM with the pinned version, when the SBOM mentions it at all.

usage: check-image-sbom-lock.py --project <csproj> --sbom <cdx.json>
exit 0 = consistent, 1 = mismatch (details on stdout), 2 = usage error
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

PROJECT_REFERENCE = re.compile(r"<ProjectReference\b[^>]*\bInclude=\"([^\"]+)\"", re.IGNORECASE)
PACKAGE_VERSION = re.compile(
    r"<(?:PackageVersion|GlobalPackageReference)\b[^>]*\bInclude=\"([^\"]+)\"[^>]*\bVersion=\"([^\"]+)\"",
    re.IGNORECASE,
)
PURL_NUGET = re.compile(r"^pkg:nuget/(?P<name>[^@]+)@(?P<version>.+)$")


def project_closure(entry: Path) -> list[Path]:
    """Entry project plus every ProjectReference, transitively."""
    seen: dict[Path, None] = {}
    queue = [entry.resolve()]
    while queue:
        project = queue.pop()
        if project in seen:
            continue
        seen[project] = None
        text = project.read_text(encoding="utf-8")
        for include in PROJECT_REFERENCE.findall(text):
            referenced = (project.parent / include.replace("\\", "/")).resolve()
            if referenced.suffix == ".csproj" and referenced not in seen:
                queue.append(referenced)
    return list(seen)


def lock_entries(projects: list[Path]) -> tuple[set[tuple[str, str]], list[str]]:
    """(id, version) pairs from the lock files of the closure; plus the files read."""
    entries: set[tuple[str, str]] = set()
    read: list[str] = []
    for project in projects:
        lock = project.parent / "packages.lock.json"
        if not lock.is_file():
            continue
        read.append(str(lock.relative_to(REPO_ROOT)))
        document = json.loads(lock.read_text(encoding="utf-8"))
        for target, packages in document.get("dependencies", {}).items():
            if not isinstance(packages, dict):
                continue
            for name, entry in packages.items():
                if not isinstance(entry, dict):
                    continue
                if entry.get("type") == "Project":
                    continue
                resolved = entry.get("resolved")
                if isinstance(resolved, str) and resolved:
                    entries.add((name.lower(), resolved))
    return entries, read


def central_versions(props: Path) -> dict[str, str]:
    if not props.is_file():
        return {}
    return {
        name.lower(): version
        for name, version in PACKAGE_VERSION.findall(props.read_text(encoding="utf-8"))
    }


def sbom_nuget_components(document: dict) -> set:
    """{(id, version)} for every NuGet component (lowercased id).

    A set of pairs, not a name -> version map: a CycloneDX document generated over
    a project graph may legitimately list the same package at two versions when two
    projects resolve different ones (measured 2026-09-27: the Api graph carries
    Microsoft.Extensions.DependencyInjection.Abstractions at both 8.0.0 and
    10.0.12), and a map would silently drop one of them.
    """
    components = set()
    for component in document.get("components", []):
        if not isinstance(component, dict):
            continue
        purl = component.get("purl") or ""
        match = PURL_NUGET.match(purl)
        name = match.group("name") if match else component.get("name")
        version = match.group("version") if match else component.get("version")
        if not isinstance(name, str) or not name:
            continue
        if not isinstance(version, str) or not version:
            continue
        components.add((name.lower(), version))
    return components


def relative_label(path: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(REPO_ROOT))
    except ValueError:
        return str(resolved)


def check(project: Path, sbom: Path) -> int:
    label = f"{relative_label(project)} vs {sbom.name}"
    if not project.is_file():
        print(f"image-sbom-lock: {project} does not exist", file=sys.stderr)
        return 2
    if not sbom.is_file():
        print(f"image-sbom-lock: {sbom} does not exist", file=sys.stderr)
        return 2

    document = json.loads(sbom.read_text(encoding="utf-8"))
    if document.get("bomFormat") != "CycloneDX" or not document.get("specVersion"):
        print(f"image-sbom-lock: {sbom} is not a CycloneDX document", file=sys.stderr)
        return 2

    entries, lock_files = lock_entries(project_closure(project))
    if not entries:
        print(f"image-sbom-lock: no resolved packages in the lock files of {project} "
              f"(nothing was read) — refusing a vacuous pass", file=sys.stderr)
        return 1

    components = sbom_nuget_components(document)
    if not components:
        print(f"image-sbom-lock: {sbom} has no NuGet component — refusing a vacuous pass",
              file=sys.stderr)
        return 1

    pins = central_versions(REPO_ROOT / "Directory.Packages.props")
    failures: list[str] = []

    # Exact equality of the (id, version) sets in both directions: the SBOM must
    # describe the graph the lock files resolve — no component the lock files do
    # not know (a stale SBOM generated before a package bump) and none missing (an
    # SBOM generated from a partial graph, e.g. without the referenced projects).
    # Measured on the three images 2026-09-27: 54 = 54 for the Api, 50 = 50 for
    # the Worker and 6 = 6 for the Migrator.
    for name, version in sorted(components - entries):
        failures.append(
            f"{name}@{version} is in the SBOM but not resolved by the lock files "
            f"(stale SBOM?)")
    for name, version in sorted(entries - components):
        failures.append(
            f"{name}@{version} is resolved by the lock files but missing from the SBOM "
            f"(incomplete SBOM)")

    sbom_versions: dict = {}
    for name, version in components:
        sbom_versions.setdefault(name, set()).add(version)
    for name, pinned in sorted(pins.items()):
        if name in sbom_versions and pinned not in sbom_versions[name]:
            failures.append(
                f"{name} is pinned to {pinned} in Directory.Packages.props but the SBOM "
                f"lists {sorted(sbom_versions[name])}")

    present_pins = sum(1 for name in pins if name in sbom_versions)

    if failures:
        for failure in failures:
            print(f"image-sbom-lock: {label}: {failure}", file=sys.stderr)
        print(f"image-sbom-lock: {len(failures)} mismatch(es)", file=sys.stderr)
        return 1

    print(f"image-sbom-lock: {label}: {len(components)} (id, version) pair(s) equal the "
          f"{len(entries)} resolved package(s) of {len(lock_files)} lock file(s); "
          f"{present_pins}/{len(pins)} Directory.Packages.props pins present")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(add_help=True)
    parser.add_argument("--project", required=True, help="entry-point .csproj of the image")
    parser.add_argument("--sbom", required=True, help="CycloneDX JSON emitted for that image")
    arguments = parser.parse_args()
    return check(Path(arguments.project), Path(arguments.sbom))


if __name__ == "__main__":
    sys.exit(main())
