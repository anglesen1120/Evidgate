#!/usr/bin/env bash
# 01.3.2-T1.3: the generated-SDK drift gate (AC1).
#
# `packages/sdk/gen/` is a committed build product of `contracts/openapi.yaml` +
# `openapi-ts.config.mjs` (see the config header for the determinism pins). This script
# regenerates it and fails when the tracked tree does not match byte-for-byte.
#
# Precondition: this script regenerates BEFORE diffing, and `git diff` compares the
# regenerated tree against the git index. It only guards committed/staged drift — it is
# a CI-and-pre-commit gate, not a guard against uncommitted local edits. An unstaged
# hand-edit to a generated file is silently overwritten by the `npm run codegen` below,
# so the gate exits 0; stage or commit the edit (or run the gate from a clean tree) for
# the check to see it. What the gate catches:
#
# - a staged/committed hand-edited generated file → `git diff` sees the change
# - a spec edit without re-running codegen        → regeneration changes the tree
# - a regenerated file that was never `git add`ed → the untracked check below
#
# The diff is scoped to `packages/sdk/gen` — the tree codegen owns (output.path +
# clean: true in openapi-ts.config.mjs). Scoping to all of `packages/sdk` would flag the
# hand-written files beside it (src/, tsconfig*.json, package.json) as drift whenever they
# carry an uncommitted edit, which is not what this gate is about. `contracts/openapi.yaml`
# is likewise out of scope: CI regenerates before diffing, so an uncommitted spec change
# still shows up here as changed generated bytes.
set -euo pipefail
cd "$(dirname "$0")/.."

npm run codegen

if ! git diff --exit-code -- packages/sdk/gen; then
  echo "check-codegen-drift: generated SDK is stale — commit 'npm run codegen' output together with the spec/change" >&2
  exit 1
fi

untracked=$(git ls-files --others --exclude-standard -- packages/sdk/gen)
if [[ -n "$untracked" ]]; then
  echo "check-codegen-drift: regenerated files are untracked — git add them:" >&2
  echo "$untracked" >&2
  exit 1
fi

echo "check-codegen-drift: packages/sdk/gen is in sync with contracts/openapi.yaml"
