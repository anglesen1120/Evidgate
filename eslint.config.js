// 01.2.1-T1: ESLint 10 flat config (CommonJS — the root package.json has no
// "type":"module" because spectral custom functions under scripts/spectral are
// CommonJS and loaded via require).
// T47: server-side (C#) boundaries are enforced by tests/Architecture.Tests, not
// ESLint — this config covers apps/web and packages/* TypeScript only (00 §5.6).
// 09.1.1-T1: apps/web is an Angular 22 application, so its TypeScript is linted with
// angular-eslint (00 §5.6 W2: standalone + OnPush, no `any`, built-in control flow, `app`
// selector prefix) and its templates with @angular-eslint/template. Two rules the story
// still owes are deliberately NOT wired here: AC3's ban on hand-written wire DTOs and on
// `HttpClient`/fetch outside core data services (plan §2 AC3), and the W1 feature→feature
// import boundary (plan §8 T47). §10 assigns only T1.2 to this config, so nothing in this
// plan owns them — they remain open for 09.1.1 AC3.
const tseslint = require('typescript-eslint');
const angular = require('angular-eslint');
// 09.1.1-T11.4 (AC9): @eslint/css is ESM-only, so its default export arrives through
// `require()` as `.default` (Node's require(esm), available since 22.12 — this repo pins
// Node 26 in .nvmrc, and the package's own engines are ^20.19 || ^22.13 || >=24).
const css = require('@eslint/css').default;
// The local `style-tokens` plugin: `no-raw-literals` for component .css files and
// `no-raw-literals-inline` for the `styles: [...]` strings of an `@Component`.
const styleTokens = require('./apps/web/eslint-rules/style-tokens.js');

// 09.1.1-T1: the Angular TypeScript rule set, shared by the application sources and the
// spec project below so a TestBed host component is held to the same rules as the app.
const angularTsRecommended = [...angular.configs.tsRecommended];

// AC3: floating promises and `any` are hard errors (npm run lint also uses
// --max-warnings 0, so a warning is already a failure; these are pinned as
// errors so the severity is explicit).
const typescriptRules = {
  '@typescript-eslint/no-floating-promises': 'error',
  '@typescript-eslint/no-explicit-any': 'error',
};

module.exports = tseslint.config(
  {
    ignores: [
      '**/node_modules/**',
      '**/dist/**',
      '**/bin/**',
      '**/obj/**',
      '**/coverage/**',
      '**/*.tsbuildinfo',
      '.husky/_/**',
      // 09.1.1-T1: the Angular CLI cache and the artefacts of `ng test` / `playwright test`
      // (`test-results/junit.xml`, `playwright-report/**`) are generated, never linted.
      '**/.angular/**',
      'apps/web/test-results/**',
      'apps/web/playwright-report/**',
      // 01.3.2-T1.1: `packages/sdk/gen` is generated by @hey-api/openapi-ts — pinned,
      // byte-exact output; lint findings there are fixed by the generator, never by hand.
      'packages/sdk/gen/**',
    ],
  },
  {
    // 09.1.1-T1: the Angular application sources (00 §5.6 W2). The project service resolves
    // each file through its nearest tsconfig, i.e. apps/web/tsconfig.json — the project the
    // emitting tsconfig.app.json extends and the builder compiles.
    files: ['apps/web/**/*.ts'],
    // 01.6.1-T1.2 / 01.6.1-T5.1: specs, the Vitest configs and the Playwright config are
    // excluded from the emitting build projects (`exclude`/`include` in every workspace
    // tsconfig.json), so the project service cannot open them. The block below types them
    // against the no-emit tsconfig.spec.json projects instead.
    ignores: ['**/*.test.ts', '**/*.spec.ts', '**/vitest.config.ts', '**/playwright.config.ts'],
    extends: [tseslint.configs.recommendedTypeChecked, ...angularTsRecommended],
    // 09.1.1-T11.4 (AC9): a component style may live inline in `styles: [...]` instead of a
    // .css file, so the same raw-literal contract is enforced on those strings here. See
    // the CSS block below for the stylesheet half of the rule.
    plugins: { 'style-tokens': styleTokens },
    // 09.1.1-T1: component templates written inline in `@Component` are extracted so the
    // angular template rules (the `*/deprecated-*` and control-flow checks) see them too.
    processor: angular.processInlineTemplates,
    languageOptions: {
      parserOptions: {
        projectService: true,
        tsconfigRootDir: __dirname,
      },
    },
    rules: {
      ...typescriptRules,
      // AC9: no raw colour/spacing literal in an inline component style.
      'style-tokens/no-raw-literals-inline': 'error',
      // W2: standalone components/directives/pipes only, no empty lifecycle hook left behind
      // by a schematic, and no component opting out of OnPush. Since Angular 22 the default
      // strategy *is* OnPush (`ChangeDetectionStrategy.Default` was renamed `Eager`), so the
      // rule reports an explicit `changeDetection: ChangeDetectionStrategy.Eager`; a component
      // that omits the property is already OnPush and is the preferred shape. An explicit
      // `OnPush` stays allowed (`allowExplicitOnPush` default) because the scaffolding
      // schematics of angular.json still write it.
      '@angular-eslint/prefer-standalone': 'error',
      '@angular-eslint/prefer-on-push-component-change-detection': 'error',
      '@angular-eslint/no-empty-lifecycle-method': 'error',
      // `angular.json` → `projects.web.prefix` is `app`: element selectors are `app-*`
      // kebab-case, attribute selectors on directives are `app*` camelCase.
      '@angular-eslint/component-selector': [
        'error',
        { type: 'element', prefix: 'app', style: 'kebab-case' },
      ],
      '@angular-eslint/directive-selector': [
        'error',
        { type: 'attribute', prefix: 'app', style: 'camelCase' },
      ],
    },
  },
  {
    // 09.1.1-T1: the component templates and the application shell's index.html. Inline
    // templates arrive here as the processor's virtual `<file>.ts/<n>_*.html` blocks, which
    // this glob also matches. Every rule of both sets reports error, so --max-warnings 0
    // holds without a separate warning budget.
    files: ['apps/web/**/*.html'],
    extends: [...angular.configs.templateRecommended, ...angular.configs.templateAccessibility],
    rules: {
      // The three rules the Angular 22 scaffolding contract names explicitly on top of the
      // recommended set: `*ngIf` / `*ngFor` are superseded by the built-in control flow, and
      // `any` and `==` are banned in bindings exactly as they are in TypeScript (AC3).
      '@angular-eslint/template/prefer-control-flow': 'error',
      '@angular-eslint/template/no-any': 'error',
      '@angular-eslint/template/eqeqeq': 'error',
    },
  },
  {
    // 09.1.1-T11.4 (AC9): component styles may reference the design tokens only. `tokens.css`
    // is the single file allowed to hold raw colour/spacing values, so it is exempt; every
    // other stylesheet under apps/web is checked by the local `style-tokens` plugin. The
    // @eslint/css language parses the file, no built-in css/* rule is enabled (the contract
    // names only this rule, and enabling more would fail unrelated CSS).
    // `@media` / `@container` / `@supports` PRELUDES are never checked by the rule: CSS
    // cannot read a custom property in a condition, so `--eg-bp-tablet`/`--eg-bp-desktop`
    // are documented literal mirrors (docs/design/web/layout.md). Declarations inside those
    // blocks are still checked.
    files: ['apps/web/**/*.css'],
    ignores: ['apps/web/src/styles/tokens.css'],
    plugins: { css, 'style-tokens': styleTokens },
    language: 'css/css',
    rules: {
      'style-tokens/no-raw-literals': 'error',
    },
  },
  {
    files: ['packages/**/*.{ts,tsx}'],
    // 01.6.1-T1.2 / 01.6.1-T5.1: the same spec/config exclusion as the apps/web block above.
    ignores: ['**/*.test.ts', '**/*.spec.ts', '**/vitest.config.ts', '**/playwright.config.ts'],
    extends: [tseslint.configs.recommendedTypeChecked],
    languageOptions: {
      parserOptions: {
        projectService: true,
        tsconfigRootDir: __dirname,
      },
    },
    rules: typescriptRules,
  },
  {
    // 01.6.1-T1.2 / 01.6.1-T5.1: `*.test.ts` (Vitest), `*.spec.ts` (the Angular component
    // specs of apps/web/src and the Playwright E2E specs of apps/web/e2e), the per-workspace
    // `vitest.config.ts` / `playwright.config.ts` and the two root Vitest configs are
    // type-checked against a no-emit tsconfig.spec.json. A project that is only referenced
    // from tsconfig.json is not visible to the project service, hence the explicit list —
    // keep it in sync with the root tsconfig.spec.json and the workspaces of the root
    // package.json. apps/web/tsconfig.spec.json is the project that includes
    // `src/**/*.spec.ts` (Angular specs) as well as `playwright.config.ts` and `e2e/**/*.ts`.
    files: [
      'vitest.config.ts',
      'vitest.config.base.mts',
      'apps/web/eslint-rules/vitest.config.mts',
      '**/*.test.ts',
      '**/*.spec.ts',
      '**/vitest.config.ts',
      '**/playwright.config.ts',
    ],
    extends: [tseslint.configs.recommendedTypeChecked, ...angularTsRecommended],
    // 09.1.1-T1: a spec may declare its own TestBed host component, so the inline templates
    // of the spec project are extracted for the angular template rules as well.
    processor: angular.processInlineTemplates,
    languageOptions: {
      parserOptions: {
        project: [
          './tsconfig.spec.json',
          './apps/web/tsconfig.spec.json',
          './packages/*/tsconfig.spec.json',
        ],
        tsconfigRootDir: __dirname,
      },
    },
    rules: {
      ...typescriptRules,
      // 09.1.1-T1: a TestBed host component declared in an apps/web spec is still application
      // code, so it is held to the W2 rules; selectors are not, a spec's test host is free to
      // name itself (it is never registered with the application).
      '@angular-eslint/prefer-standalone': 'error',
      '@angular-eslint/prefer-on-push-component-change-detection': 'error',
      '@angular-eslint/no-empty-lifecycle-method': 'error',
      '@angular-eslint/component-selector': 'off',
      '@angular-eslint/directive-selector': 'off',
    },
  },
);
